// Regenerates src/kernels.wasm.ts (the embedded module) from wasm/kernels.wasm.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const bytes = readFileSync(new URL("../wasm/kernels.wasm", import.meta.url));
const sha = createHash("sha256").update(bytes).digest("hex").slice(0, 16);
const body = `// GENERATED by scripts/embed.mjs from wasm/kernels.wasm (${bytes.length} bytes, sha256 ${sha}). Do not edit.
// Embedded so the module loads in Node, workers and browsers without a fetch.
export const KERNELS_WASM_BASE64 =
  "${bytes.toString("base64")}";
`;
writeFileSync(new URL("../src/kernels.wasm.ts", import.meta.url), body);
