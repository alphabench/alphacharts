#!/usr/bin/env node
// Writes src/ui/icons.generated.ts: the Lucide icons the shell uses (shadcn/ui's icon library), as plain data, so the package
// carries no runtime dependency on Lucide. Lucide is ISC licensed; its notice is in the repository's NOTICE file.
// Our own name on the left, the Lucide icon on the right. Icons Lucide has no equivalent for (a pitchfork, a Fibonacci fan, a
// long position) stay our own, drawn in src/ui/icons.tsx on the same 24 grid and stroke.
//
//   node scripts/gen-icons.mjs        (from packages/ui; needs the `lucide` devDependency installed)

import { writeFileSync } from "node:fs";
import { icons } from "lucide";

const MAP = {
  search: "Search", plus: "Plus", close: "X", check: "Check", chevron: "ChevronDown", chevronRight: "ChevronRight",
  undo: "Undo2", redo: "Redo2", camera: "Camera", expand: "Maximize", shrink: "Minimize", gear: "Settings", layout: "LayoutGrid",
  bell: "Bell", indicators: "ChartLine", compare: "ArrowLeftRight", star: "Star", trash: "Trash2", lock: "Lock", unlock: "LockOpen",
  eye: "Eye", eyeOff: "EyeOff", snapIndicators: "ChartSpline", magnet: "Magnet", cursor: "MousePointer2", cross: "Plus",
  trend: "Slash", hline: "Minus", ray: "MoveUpRight", pattern: "Waypoints", shape: "Square", circle: "Circle", text: "Type",
  note: "StickyNote", arrow: "ArrowUpRight", flag: "Flag", measure: "Ruler", more: "Ellipsis", sun: "Sun", moon: "Moon", globe: "Globe",
  code: "CodeXml", play: "Play", copy: "Copy", chartType: "ChartCandlestick", save: "Save", grid: "LayoutGrid", list: "List",
  keep: "Repeat", pencil: "Pencil", rectangle: "Square", info: "Info", success: "CircleCheck", error: "OctagonX",
  // drawing tools Lucide draws well; the rest are ours (src/ui/icons.tsx)
  triangle: "Triangle", curve: "Spline", path: "Route", brush: "Brush", highlighter: "Highlighter",
  anchoredText: "LetterText", anchoredNote: "NotepadText", callout: "MessageSquare", comment: "MessageCircle", priceLabel: "Tag",
  priceNote: "Tags", signpost: "Signpost", flagMark: "Flag", arrowMarker: "MoveUpRight", arrowMarkUp: "ArrowBigUp",
  arrowMarkDown: "ArrowBigDown", arrowMarkLeft: "ArrowBigLeft", arrowMarkRight: "ArrowBigRight", pin: "MapPin", table: "Table",
  icon: "Smile", ghostFeed: "Ghost", sector: "ChartPie",
};
const out = {};
for (const [ours, theirs] of Object.entries(MAP)) {
  const node = icons[theirs];
  if (!node) throw new Error(`gen-icons: Lucide has no icon "${theirs}" (for "${ours}")`);
  out[ours] = node;
}
const body = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join("\n");
writeFileSync(new URL("../src/ui/icons.generated.ts", import.meta.url), `// Generated by scripts/gen-icons.mjs from Lucide (ISC licence, https://lucide.dev). Do not edit by hand.\n\nexport type IconNode = ReadonlyArray<readonly [tag: string, attrs: Readonly<Record<string, string>>]>;\n\nexport const LUCIDE: Record<string, IconNode> = {\n${body}\n};\n`);
console.log(`wrote ${Object.keys(out).length} icons`);
