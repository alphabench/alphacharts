#!/usr/bin/env node
// The TradingView parity measure: `node scripts/tv-parity.mjs [--check]`.
//
// Reads the catalogue (scripts/lib/tv-catalogue.mjs), looks every mapped id up in the built packages and the
// sources, and writes docs/PARITY.md. An item is "have" only when its id is found; a mapped id that is not
// found is an error (the catalogue is stale or an id was renamed). With --check nothing is written: it fails
// on a broken mapping or when docs/PARITY.md is not what the catalogue and the code produce now.
// Needs the built packages (pnpm build), like the skill checker.

import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { CHART_TYPES, CHART_TYPES_DEFER, DRAWINGS, DRAWINGS_CUT, FEATURES, FEATURES_DEFER, STUDIES, STUDIES_DEFER } from "./lib/tv-catalogue.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "docs", "PARITY.md");
const dist = (pkg, file) => {
  const p = join(ROOT, "packages", pkg, "dist", file);
  if (!existsSync(p)) throw new Error(`packages/${pkg}/dist/${file} is missing: run pnpm build`);
  return pathToFileURL(p).href;
};

const errors = [];
/** A word in a comment is not a feature: look only at code. */
const stripComments = (t) => t.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:])\/\/.*$/gm, "$1");
const drawingIds = new Set((await import(dist("drawings", "index.js"))).allTools.map((t) => t.id));
const ind = await import(dist("indicators", "index.js"));
(await import(dist("indicators", "all.js"))).registerAllStudies();
const ext = await import(dist("extend", "index.js"));
// Analyses are offered next to studies in the picker, so a study row may map to one (the auto-drawing ones).
const studyIds = new Set([...ind.listStudies().map((s) => s.id), ...ext.autoDrawings().map((a) => a.manifest.id)]);
const chartTypeIds = new Set([...readFileSync(join(ROOT, "packages/ui/src/model/chartTypes.ts"), "utf8").matchAll(/\{ id: "(\w+)", key: "chartType\./g)].map((m) => m[1]));
if (!drawingIds.size || !studyIds.size || !chartTypeIds.size) throw new Error("an id table is empty: the check would pass on nothing");

/** One row: have / gap / cut-or-defer, and an error when a mapped id does not exist. */
function status(kind, known, [name, id, note], decided) {
  if (id !== null) {
    if (!known.has(id)) { errors.push(`${kind} "${name}" maps to "${id}", which does not exist`); return { name, state: "BROKEN", detail: id }; }
    return { name, state: "have", detail: id, note };
  }
  if (name in decided) return { name, state: "decided", detail: decided[name] };
  return { name, state: "gap", detail: note ?? "" };
}
const section = (kind, groups, known, decided) => Object.entries(groups).map(([group, rows]) => ({ group, rows: rows.map((r) => status(kind, known, r, decided)) }));

const drawings = section("drawing", DRAWINGS, drawingIds, DRAWINGS_CUT);
const studies = section("study", STUDIES, studyIds, STUDIES_DEFER);
const chartTypes = [{ group: "Chart types", rows: CHART_TYPES.map((r) => status("chart type", chartTypeIds, r, CHART_TYPES_DEFER)) }];
const features = [{
  group: "Chart features",
  rows: FEATURES.map(([name, where]) => {
    if (!where) return name in FEATURES_DEFER ? { name, state: "decided", detail: FEATURES_DEFER[name] } : { name, state: "gap", detail: "" };
    const [file, word] = where;
    const p = join(ROOT, "packages", file);
    if (!existsSync(p)) { errors.push(`feature "${name}": packages/${file} does not exist`); return { name, state: "BROKEN", detail: file }; }
    if (!word) { errors.push(`feature "${name}": the catalogue row names no word to look for`); return { name, state: "BROKEN", detail: file }; }
    if (!stripComments(readFileSync(p, "utf8")).includes(word)) { errors.push(`feature "${name}": packages/${file} no longer mentions ${JSON.stringify(word)} outside comments`); return { name, state: "BROKEN", detail: file }; }
    return { name, state: "have", detail: file };
  }),
}];

const all = [...drawings, ...studies, ...chartTypes, ...features];
const count = (groups, s) => groups.flatMap((g) => g.rows).filter((r) => r.state === s).length;
const total = (groups) => groups.flatMap((g) => g.rows).length;

const md = [];
md.push("# TradingView parity", "", "Generated by `node scripts/tv-parity.mjs` from `scripts/lib/tv-catalogue.mjs` and the built packages. Do not edit by hand.", "",
  "`have`: the id is found in the built package or source. `gap`: not built. `decided`: a gap left by decision, with the reason.", "",
  "| Area | Items | have | gap | decided |", "|---|---:|---:|---:|---:|");
for (const [label, g] of [["Drawing tools", drawings], ["Indicators", studies], ["Chart types", chartTypes], ["Chart features", features]]) {
  md.push(`| ${label} | ${total(g)} | ${count(g, "have")} | ${count(g, "gap")} | ${count(g, "decided")} |`);
}
md.push("", `Not in the catalogue, built here anyway: ${drawingIds.size - new Set(drawings.flatMap((g) => g.rows).filter((r) => r.state === "have").map((r) => r.detail)).size} drawing tools and ${studyIds.size} studies in total (the TA-Lib set and \`cdl-*\` patterns are mostly outside TradingView's built-in list).`, "");
for (const [title, groups] of [["Drawing tools", drawings], ["Indicators", studies], ["Chart types", chartTypes], ["Chart features", features]]) {
  md.push(`## ${title}`, "");
  for (const { group, rows } of groups) {
    md.push(`### ${group}`, "", "| TradingView | State | Here |", "|---|---|---|");
    for (const r of rows) md.push(`| ${r.name} | ${r.state} | ${r.detail}${r.note ? ` (${r.note})` : ""} |`);
    md.push("");
  }
}
const text = md.join("\n");

const check = process.argv.includes("--check");
if (check) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) errors.push("docs/PARITY.md is stale: run node scripts/tv-parity.mjs");
} else if (!errors.length) {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
}
for (const g of [drawings, studies, chartTypes, features]) console.log(`${String(total(g)).padStart(4)} items, ${count(g, "have")} have, ${count(g, "gap")} gap, ${count(g, "decided")} decided`);
if (errors.length) { console.error(errors.join("\n")); process.exit(1); }
void all;
