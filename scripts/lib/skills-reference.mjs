// The generated part of the skills: the per-study reference (split by family, so a model loads only what it needs)
// and the builtins reference, both rendered from the real tables: `listStudies()` and builtins.ts. Pure: returns text.

import { createHash } from "node:crypto";
import { extractDiagnostics } from "./skills-engine.mjs";

export const BANNER = "<!-- Generated by scripts/gen-skill-reference.mjs from the study registry and builtins.ts. Do not edit: change the source and run pnpm gen:skills. -->";

/** Where the language itself says the tuple of a kernel comes out (it has no study to read the columns from). */
export const KERNEL_OUTPUTS = { "ta.bb": ["basis", "upper", "lower"] };

const FAMILIES = [
  ["overlap", "Overlap: moving averages, bands, SAR"],
  ["momentum", "Momentum and trend strength"],
  ["volatility", "Volatility"],
  ["volume", "Volume"],
  ["price", "Price transforms"],
  ["statistic", "Statistics"],
  ["cycle", "Cycle (Hilbert)"],
  ["tv", "TradingView set: channels, trend, oscillators, levels"],
  ["pattern", "Candlestick patterns"],
];
export const FAMILY_FILES = Object.fromEntries([...FAMILIES.map(([f]) => [f, `studies/reference/${f}.md`]), ["math", "studies/reference/math.md"]]);
export const BUILTINS_FILE = "script-language/reference/builtins.md";

const fnName = (id) => `ta.${id.replace(/-/g, "_")}`;
const num = (x) => (Number.isInteger(x) ? String(x) : String(+x.toPrecision(12)));

function paramText(p) {
  const i = p.input;
  const t = p.kind === "num" ? "float" : p.kind === "string" && p.oneOf ? "select" : p.kind;
  let s = `${p.name}:${t}`;
  if (i !== undefined) s += `=${typeof i.default === "number" ? num(i.default) : String(i.default)}`;
  if (p.kind === "string" && p.oneOf) s += `{${p.oneOf.join("|")}}`;
  if (p.kind === "int" || p.kind === "num") {
    const lo = p.min, hi = p.max;
    if (lo !== undefined || hi !== undefined) s += `[${lo === undefined ? "" : num(lo)}..${hi === undefined ? "" : num(hi)}]`;
  }
  return s;
}

function studyLine(sig, def, outputs, blocked) {
  const params = sig.params.map(paramText).join(", ");
  const out = outputs.length === 1 && !sig.ret.elems ? "series" : `[${outputs.join(", ")}]`;
  const bits = [def?.pane === "overlay" ? "overlay" : def ? "own pane" : null, (sig.needs ?? def?.needs) === "ohlcv" ? "needs volume" : (sig.needs ?? def?.needs) === "ohlc" ? "needs ohlc" : null].filter(Boolean);
  const note = blocked ? " · NOT CALLABLE: the name is a reserved word of the language, so it cannot be written" : "";
  return `- \`${sig.name}(${params})\` -> ${out}${bits.length ? ` · ${bits.join(" · ")}` : ""} · ${def ? def.name : ""}${note}`.replace(/ · $/, "");
}

/** Everything generated, as a map from path (relative to the skills directory) to text, plus the facts the checker needs. */
export function renderReference({ studies, builtins, words }) {
  const { SIGS, BUILTIN_SERIES, MEMBER_CONSTS, COLORS } = builtins;
  const files = new Map();
  const byFamily = new Map();
  const kernelOnly = [];
  const callable = new Set();
  const unwritable = [];
  const studyByFn = new Map(studies.filter((s) => s.family !== "math").map((s) => [fnName(s.id), s]));

  for (const sig of SIGS.values()) {
    if (!sig.name.startsWith("ta.")) continue;
    const def = sig.study ?? studyByFn.get(sig.name);
    if (!def) {
      kernelOnly.push(sig);
      continue;
    }
    const outputs = sig.op === "study" ? [...def.columns] : (KERNEL_OUTPUTS[sig.name] ?? [...def.columns]);
    if (!byFamily.has(def.family)) byFamily.set(def.family, []);
    const blocked = words.has(sig.name.slice(3));
    byFamily.get(def.family).push({ sig, def, outputs, blocked });
    if (blocked) unwritable.push(sig.name);
    else callable.add(sig.name);
  }

  const legend = [
    "Line: `ta.name(parameters) -> outputs · placement · needs · title`. Legend in the studies skill: `name:type=default[min..max]`, `select` shows `{allowed|strings}`, no `=default` means required, `[a, b]` is a tuple to destructure in that order.",
  ];
  for (const [fam, title] of FAMILIES) {
    const rows = byFamily.get(fam) ?? [];
    const out = [BANNER, "", `# Studies: ${title}`, "", ...legend, ""];
    if (fam === "pattern") {
      const plain = rows.filter((r) => r.sig.params.length === 0 && r.outputs.join() === "signal");
      const rest = rows.filter((r) => !plain.includes(r));
      if (rest.some((r) => r.outputs.join() !== "signal")) throw new Error("a pattern study has more than the `signal` output: rewrite the pattern renderer");
      out.push("Every pattern returns one series (`signal`): `na` while warming up, `0` for no pattern, a positive value for a bullish pattern and a negative one for a bearish pattern (the size is the strength: 100 is a full signal, an engulfing also returns 80; neutral patterns such as the doji return 100). Test it with a comparison, `ta.cdl_doji() != 0`.", "", "Patterns with parameters:", "", ...rest.map((r) => studyLine(r.sig, r.def, r.outputs)), "", "Patterns with no arguments, written `ta.<name>()`:", "");
      for (const r of plain) out.push(`- \`${r.sig.name}()\` · ${r.def.name}`);
    } else {
      for (const r of rows) out.push(studyLine(r.sig, r.def, r.outputs, r.blocked));
    }
    out.push("");
    files.set(FAMILY_FILES[fam], out.join("\n"));
  }
  const unplaced = [...byFamily.keys()].filter((f) => !FAMILIES.some(([x]) => x === f));
  if (unplaced.length) throw new Error(`studies in a family with no reference file: ${unplaced.join(", ")}`);

  const math = studies.filter((s) => s.family === "math");
  files.set(FAMILY_FILES.math, [BANNER, "", "# Studies: math transforms and operators", "", "These registry studies are not callable as `ta.*`: the language has no `ta.<id>` for the family. Use `math.*` or an operator (see the studies skill).", "", math.map((s) => `\`${s.id}\``).join(", "), ""].join("\n"));

  // ---- builtins
  const b = [BANNER, "", "# Language builtins", "", "Signatures are the checker's own table: `name(parameter:kind...)`. `?` marks an optional parameter. Kinds: `series` any numeric series; `int` / `float` / `bool` / `string` / `color` a literal or an `input.*` (never a series); `plot` a handle from `p = plot(...)`; `any` a value; `strlist` an array literal of strings; `enum` one of the named constants. `[a..b]` is the accepted range of a literal.", ""];
  b.push("## Series", "");
  b.push(Object.entries(BUILTIN_SERIES).map(([k, v]) => `\`${k}\` (${v.ty.b} series${v.needs === "ohlcv" ? ", needs volume" : v.needs === "ohlc" ? ", needs ohlc" : ""})`).join(", ") + ", `ta.tr` (float series, needs ohlc).", "");
  const sigLine = (s) => {
    const ps = s.params.map((p) => {
      let t = p.kind === "num" ? "float" : p.kind;
      if (p.kind === "enum") t = `enum {${Object.keys(MEMBER_CONSTS).filter((k) => k.split(".")[0] === enumNs(p, MEMBER_CONSTS)).join("|")}}`;
      let r = "";
      if ((p.kind === "int" || p.kind === "num") && (p.min !== undefined || p.max !== undefined)) r = `[${p.min === undefined ? "" : num(p.min)}..${p.max === undefined ? "" : num(p.max)}]`;
      return `${p.name}${p.opt ? "?" : ""}:${t}${r}`;
    });
    const ret = s.ret.b === "tuple" ? `[${(KERNEL_OUTPUTS[s.name] ?? s.ret.elems.map(() => "float")).join(", ")}]` : s.ret.b === "void" ? "nothing" : s.ret.b === "plot" ? "plot handle" : `${s.ret.q === "series" ? "series " : ""}${s.ret.b}`;
    return `- \`${s.name}(${ps.join(", ")})\` -> ${ret}${s.needs ? ` · needs ${s.needs}` : ""}`;
  };
  const group = (title, pred) => {
    const list = [...SIGS.values()].filter(pred);
    if (!list.length) return;
    b.push(`## ${title}`, "", ...list.map(sigLine), "");
  };
  group("Math and helpers", (s) => s.name.startsWith("math.") || s.name === "nz" || s.name === "na");
  group("Built-in ta.* kernels with no study of the same name", (s) => kernelOnly.includes(s));
  group("Declarations and output", (s) => ["indicator", "plot", "hline", "fill", "plotshape", "color.new"].includes(s.name));
  group("Inputs", (s) => s.name.startsWith("input."));
  b.push("## Constants", "");
  const ns = {};
  for (const [k, v] of Object.entries(MEMBER_CONSTS)) {
    const [n] = k.split(".");
    if (n === "color") continue;
    (ns[n] ??= []).push(`\`${k}\``);
  }
  for (const [n, list] of Object.entries(ns)) b.push(`- ${n}: ${list.join(", ")}`);
  b.push(`- color: ${Object.keys(COLORS).map((c) => `\`color.${c}\``).join(", ")} (also \`#rrggbb\` and \`#rrggbbaa\` literals)`, "");
  files.set(BUILTINS_FILE, b.join("\n"));

  const facts = {
    callable: [...callable],
    unwritable,
    kernelOnly: kernelOnly.map((s) => s.name),
    mathIds: math.map((s) => s.id),
    studyCount: studies.length,
  };
  return { files, facts };
}

function enumNs(p, consts) {
  const first = consts && Object.keys(consts).find((k) => consts[k].value === p.oneOf[0]);
  return first ? first.split(".")[0] : "";
}

/** Fingerprint of the language: builtins, study signatures and diagnostics. The manifest records it; a language change moves it. */
export function languageSha256({ files }, root) {
  const h = createHash("sha256");
  for (const k of [...files.keys()].sort()) h.update(k).update("\0").update(files.get(k)).update("\0");
  const d = extractDiagnostics(root).diagnostics.map((x) => x.template).sort();
  h.update(d.join("\n"));
  return h.digest("hex");
}

const DOMAIN_PREFIX = "alphacharts-";
/** INDEX.md registry block from the manifest. */
export function renderRegistry(skills) {
  const out = [];
  for (const s of skills) {
    out.push(`## ${s.title}`, "", s.description, "", `Name: \`${s.name}\`  `, `Path: [${s.path}](${s.path})  `, `Status: ${s.status}  `, `API version: ${s.api_version}  `, `Depends on: ${s.depends_on.join(", ") || "none"}`, "", "Load when:", "", ...s.load_when.map((w) => `- ${w}`), "");
  }
  return out.join("\n");
}
