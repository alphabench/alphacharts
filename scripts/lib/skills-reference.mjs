/** Copies of script files embedded in a SKILL.md: the fence below `<!-- skill: file: path -->` holds the file's text. */
export function syncFileBlocks(text, readFile) {
  const lines = text.split("\n");
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    out.push(lines[i]);
    const m = /^<!--\s*skill:\s*file:\s*(\S+)\s*-->$/.exec(lines[i].trim());
    if (!m) continue;
    let j = i + 1;
    while (j < lines.length && !lines[j].trim()) out.push(lines[j++]);
    const open = /^(```|~~~)/.exec(lines[j] ?? "");
    if (!open) throw new Error(`file marker for ${m[1]} is not followed by a fenced block`);
    let k = j + 1;
    while (k < lines.length && !lines[k].startsWith(open[1])) k++;
    out.push(lines[j], ...readFile(m[1]).replace(/\n+$/, "").split("\n"), lines[k]);
    i = k;
  }
  return out.join("\n");
}
